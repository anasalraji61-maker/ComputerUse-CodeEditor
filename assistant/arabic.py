"""مساعد مشترك لاتفاق العدد والمعدود في الرسائل العربية (1 «عنصر واحد»، 2 «عنصران»، 3-10 «5 عناصر»، 11+ «12 عنصراً»).

الحالات: "nom" (مرفوع: المطلوب عملية واحدة / عمليتان)، "acc" (منصوب: يحوي عنصراً واحداً / عنصرين)، "gen" (مجرور: من خطوتين).
جدول الوحدات نسخة من assistant/models/rules.py (_UNITS/_n) ليستورد منه لاحقاً."""
from typing import Dict, Tuple

# kind: (واحد مرفوع، واحد منصوب، مثنى مرفوع، مثنى منصوب/مجرور، جمع 3-10، تمييز 11+)
UNITS: Dict[str, Tuple[str, str, str, str, str, str]] = {
    "ملف": ("ملف واحد", "ملفاً واحداً", "ملفان", "ملفين", "ملفات", "ملفاً"),
    "عنصر": ("عنصر واحد", "عنصراً واحداً", "عنصران", "عنصرين", "عناصر", "عنصراً"),
    "عملية": ("عملية واحدة", "عملية واحدة", "عمليتان", "عمليتين", "عمليات", "عملية"),
    "مجموعة": ("مجموعة واحدة", "مجموعة واحدة", "مجموعتان", "مجموعتين", "مجموعات", "مجموعة"),
    "خطوة": ("خطوة واحدة", "خطوة واحدة", "خطوتان", "خطوتين", "خطوات", "خطوة"),
    "نسخة": ("نسخة واحدة", "نسخة واحدة", "نسختان", "نسختين", "نسخ", "نسخة"),
    "مجلد": ("مجلد واحد", "مجلداً واحداً", "مجلدان", "مجلدين", "مجلدات", "مجلداً"),
}


def n_units(n: int, kind: str, case: str = "nom") -> str:
    """العدد مع المعدود بالإعراب الصحيح؛ case: nom | acc | gen (الأخيران يشتركان في المثنى «ين»، والمنصوب وحده «عنصراً واحداً»)."""
    one, one_acc, two, two_obl, few, many = UNITS[kind]
    n = int(n)
    if n == 1:
        return one_acc if case == "acc" else one
    if n == 2:
        return two if case == "nom" else two_obl
    return f"{n} {few}" if 0 <= n <= 10 else f"{n} {many}"


_n = n_units   # اسم الدالة في rules.py (توافق عند الاستيراد لاحقاً)
